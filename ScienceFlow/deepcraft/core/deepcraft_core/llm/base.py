@dataclass
class GuardStreamChunk:
    """Stream text consumed by guards but hidden from user-facing output and logs."""

    text: str
    channel: str


@dataclass
class StreamHandle:
    """Per-call streaming control — owns the chunk queue and interrupt signal.

    Each concurrent ``ask()`` call receives its own ``StreamHandle``, so
    interrupt / queue operations never interfere across calls even when
    they share the same LLM instance.
    """
    queue: asyncio.Queue = field(default_factory=asyncio.Queue)
    _event: asyncio.Event = field(default_factory=asyncio.Event)
    _eos_sent: bool = field(default=False, repr=False)

    @property
    def interrupted(self) -> bool:
        return self._event.is_set()

    def interrupt(self) -> None:
        """Signal the stream to stop.  Idempotent, sync-safe (``put_nowait``)."""
        if self._event.is_set():
            return
        self._event.set()
        while not self.queue.empty():
            try:
                self.queue.get_nowait()
            except asyncio.QueueEmpty:
                break
        if not self._eos_sent:
            self._eos_sent = True
            self.queue.put_nowait(None)

    def stop(self) -> None:
        """Signal stop: block further ``put`` and enqueue EOS, but keep pending chunks.

        Use after streaming the first complete tool call so the consumer can still
        print queued previews (``→ tool`` / JSON fragments).  Unlike ``interrupt()``,
        does **not** drain the queue.  Idempotent.
        """
        if self._event.is_set():
            return
        self._event.set()
        if not self._eos_sent:
            self._eos_sent = True
            self.queue.put_nowait(None)

    async def put(self, chunk: str | None) -> None:
        """Enqueue a chunk.  No-op after ``interrupt`` / ``stop`` to prevent late writes."""
        if not self._event.is_set():
            await self.queue.put(chunk)

    async def put_guard(self, chunk: str, *, channel: str) -> None:
        """Enqueue hidden text for stream guards without rendering or logging it."""
        if chunk and not self._event.is_set():
            await self.queue.put(GuardStreamChunk(text=chunk, channel=channel))

    def finish(self) -> None:
        """Signal normal end-of-stream.  Idempotent (at most one EOS sentinel)."""
        if self._eos_sent:
            return
        self._eos_sent = True
        if not self._event.is_set():
            self.queue.put_nowait(None)


@dataclass
class CallStats:
    """Per-call LLM statistics, stored in ContextVar for concurrency safety."""
    input_tokens: int = 0
    output_tokens: int = 0
    ttft: float = 0.0
    tpot: float = 0.0
    finish_reason: str = "unknown"
    # Tokens served from provider-side prompt prefix cache (real value reported by API).
    input_cached_tokens: int = 0


_call_stats_store: contextvars.ContextVar[dict[int, CallStats]] = contextvars.ContextVar(
    "_call_stats_store",
)

