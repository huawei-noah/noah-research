class BaseLLM(BaseModel, ABC):
    '''
        base class for language model.
    model : The name of the language model to use for text completion.
    api_key : API key (default is None).
    base_url : The base URL for API requests.
    max_tokens : The maximum number of tokens in the generated completion.
    api_version : API version (default is None)
    temperature : The temperature parameter for controlling the randomness of the output .
    top_p : The top-p parameter for controlling the diversity of the output.
    headers : Additional headers to include in API requests.
    stream : Whether to stream the output or not. (default is True)
    tracker : Whether to track the usage of tokens or not. (default is False)
    '''
    model: Optional[str] = Field(default=None, description="model")
    api_type: Optional[str] = Field(default=None, description="api_type")
    api_key: Optional[str] = Field(default=None, description="api_key")
    base_url: Optional[str] = Field(default=None, description="base_url")
    max_tokens: Optional[int] = Field(default=4096, description="max_tokens")
    api_version: Optional[str] = Field(default=None, description="api_version")
    temperature: Optional[float] = Field(default=0.0, description="temperature")
    top_p: Optional[float] = Field(default=0.001, description="top_p")
    frequency_penalty: Optional[float] = Field(
        default=None,
        description="Penalty for repeated tokens (OpenAI-compatible APIs).",
    )
    headers: Optional[dict] = Field(default={}, description="headers")
    stream: Optional[bool] = Field(default=True, description="stream")
    tracker: Optional[bool] = Field(default=False, description="tracker")
    interrupted: Optional[bool] = Field(default=False, description="interrupted")
    reasoning_effort: Optional[str] = Field(
        default=None,
        description="Thinking budget for reasoning models (Gemini: minimal/low/medium/high). "
                    "Only sent to Gemini models; ignored for others."
    )
    chinese_token_ratio: float = Field(
        default=0.6, description="Avg number of tokens per Chinese Charactor, from https://api-docs.deepseek.com/quick_start/token_usage")
    english_token_ratio: float = Field(
        default=0.3, description="Avg number of tokens per English Charactor, from https://api-docs.deepseek.com/quick_start/token_usage")
    symbol_token_ratio: float = Field(
        default=1.0, description="Fallback: tokens per symbol when not using tiktoken. Use 0.33 for better heuristic (symbols often merge).")
    use_tiktoken_for_estimation: bool = Field(
        default=True, description="Use tiktoken for token count when model/encoding is set (accurate for OpenAI-compatible APIs).")
    tiktoken_encoding: Optional[str] = Field(
        default=None, description="tiktoken encoding name (e.g. cl100k_base). Overrides model when set.")
    # Configure a custom httpx client.
    # We provide a `DefaultHttpxClient` class that you can pass to retain the default values we use for `limits`, `timeout` & `follow_redirects`.
    # See the [httpx documentation](https://www.python-httpx.org/api/#client) for more details.
    http_asyncclient: Optional[httpx.AsyncClient] = Field(default=None, description="httpx asyncclient")
    usage_tracker: Optional[TokenUsageTracker] = Field(default_factory=TokenUsageTracker, description="Token Usage Tracker")
    chunk_queue: asyncio.Queue = Field(default_factory=asyncio.Queue, exclude=True, description="chunk queue")

    model_config = ConfigDict(arbitrary_types_allowed=True)

    @model_validator(mode="after")
    def initialize(self) -> "BaseLLM":
        self.usage_tracker = TokenUsageTracker()
        self.chunk_queue = asyncio.Queue()
        return self

    # ------------------------------------------------------------------
    # Per-call stats (ContextVar-backed, concurrency-safe)
    # ------------------------------------------------------------------

    def _save_call_stats(self, stats: CallStats) -> None:
        try:
            store = _call_stats_store.get()
        except LookupError:
            store = {}
            _call_stats_store.set(store)
        store[id(self)] = stats

    def _get_call_stats(self) -> CallStats:
        try:
            return _call_stats_store.get().get(id(self), CallStats())
        except LookupError:
            return CallStats()

    @property
    def _last_call_input_tokens(self) -> int:
        return self._get_call_stats().input_tokens

    @property
    def _last_call_output_tokens(self) -> int:
        return self._get_call_stats().output_tokens

    @property
    def _last_call_ttft(self) -> float:
        return self._get_call_stats().ttft

    @property
    def _last_call_tpot(self) -> float:
        return self._get_call_stats().tpot

    @property
    def _last_call_input_cached_tokens(self) -> int:
        return self._get_call_stats().input_cached_tokens

    @property
    def _last_finish_reason(self) -> str:
        return self._get_call_stats().finish_reason

    def estimate_tokens(self, text: str) -> int:
        """
        Estimate token count for text. Uses tiktoken when available and configured,
        otherwise falls back to character-ratio heuristic (chinese/english/symbol).
        """
        from .utils import estimate_tokens as _estimate_tokens
        return _estimate_tokens(
            text,
            model=self.model,
            encoding_name=self.tiktoken_encoding,
            use_tiktoken=self.use_tiktoken_for_estimation,
            fallback_chinese_ratio=self.chinese_token_ratio,
            fallback_english_ratio=self.english_token_ratio,
            fallback_symbol_ratio=self.symbol_token_ratio,
        )

    @staticmethod
    def format_messages(messages: List[Union[dict, Message]]) -> List[dict]:
        """
        Format messages for LLM by converting them to OpenAI message format.

        Args:
            messages: List of messages that can be either dict or Message objects

        Returns:
            List[dict]: List of formatted messages in OpenAI format

        Raises:
            ValueError: If messages are invalid or missing required fields
            TypeError: If unsupported message types are provided

        Examples:
            >>> msgs = [
            ...     Message.system_message("You are a helpful assistant"),
            ...     {"role": "user", "content": "Hello"},
            ...     Message.user_message("How are you?")
            ... ]
            >>> formatted = LLM.format_messages(msgs)
        """
        formatted_messages = []

        for message in messages:
            if isinstance(message, Message):
                message = message.to_dict()

            if isinstance(message, dict):
                # If message is a dict, ensure it has required fields
                if "role" not in message:
                    raise ValueError("Message dict must contain 'role' field")

                if (
                    "content" in message
                    or "tool_calls" in message
                    or message.get("reasoning_content") is not None
                ):
                    formatted_messages.append(message)

                # else: do not include the message
            else:
                raise TypeError(f"Unsupported message type: {type(message)}")

        # Validate all messages have required fields
        for msg in formatted_messages:
            if msg["role"] not in ROLE_VALUES:
                raise ValueError(f"Invalid role: {msg['role']}")

        return formatted_messages

