    def token_tracker(
            self,
            prompt_tokens,
            completion_tokens
    ):
        usage_record=None  # Initialize the return value
        if self.tracker:
            # Extract token usage from response
            input_tokens = int(prompt_tokens)
            output_tokens = int(completion_tokens)

            # Track token usage and calculate cost
            usage_record = self.usage_tracker.add_usage(
                self.model,
                input_tokens,
                output_tokens
            )

        return usage_record

    async def interrupt(self):
        """Interrupt the current generation process.

        .. deprecated::
            Use ``StreamHandle.interrupt()`` instead for per-call control.
            This instance-level method is kept for backward compatibility only.
        """
        self.interrupted = True
        if self.chunk_queue:
            while not self.chunk_queue.empty():
                try:
                    self.chunk_queue.get_nowait()
                except asyncio.QueueEmpty:
                    break
            await self.chunk_queue.put(None)
